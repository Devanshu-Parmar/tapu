const { contextBridge, ipcRenderer, webUtils } = require('electron');

const on = (channel) => (cb) => ipcRenderer.on(channel, (_e, payload) => cb(payload));
// For panels that open and close many times: the newest listener replaces the last one.
const only = (channel) => (cb) => { ipcRenderer.removeAllListeners(channel); ipcRenderer.on(channel, (_e, payload) => cb(payload)); };

contextBridge.exposeInMainWorld('island', {
  zone: (z) => ipcRenderer.send('zone', z),
  onHover: (cb) => ipcRenderer.on('hover', (_e, inside) => cb(!!inside)),
  onBlur: (cb) => ipcRenderer.on('blur', () => cb()),
  onShow: (cb) => ipcRenderer.on('show', () => cb()),
  state: () => ipcRenderer.invoke('state'),
  onMedia: on('media'),
  onWeather: on('weather'),
  onClips: on('clips'),
  onClaude: on('claude'),
  onVolume: on('volume'),
  onRecording: on('recording'),
  onRecordingDone: on('recording-done'),
  onSystem: on('system'),
  toggleRecording: () => ipcRenderer.invoke('record-toggle'),
  rates: () => ipcRenderer.invoke('rates'),
  onLyrics: on('lyrics'),
  seek: (seconds) => ipcRenderer.send('media-seek', seconds),
  setVolume: (level) => ipcRenderer.send('volume-set', level),
  toggleMute: () => ipcRenderer.send('volume-mute'),
  openSource: () => ipcRenderer.send('media-open'),
  onVoice: on('voice'),
  onVoiceResult: on('voice-result'),
  onVoicePartial: on('voice-partial'),
  voiceInfo: () => ipcRenderer.invoke('voice-info'),
  voiceStart: () => ipcRenderer.invoke('voice-start'),
  voiceStop: () => ipcRenderer.invoke('voice-stop'),
  voiceSet: (mic, lang) => ipcRenderer.send('voice-set', mic, lang),
  claudeUsage: () => ipcRenderer.invoke('claude-usage'),
  media: (cmd) => ipcRenderer.send('media-cmd', cmd),
  log: (text) => ipcRenderer.send('log', text),
  quit: () => ipcRenderer.send('quit'),

  load: (key) => ipcRenderer.invoke('store-get', key),
  save: (key, value) => ipcRenderer.send('store-set', key, value),
  onStoreChanged: on('store-changed'),

  copyClip: (text) => ipcRenderer.send('clip-copy', text),
  clearClips: () => ipcRenderer.send('clip-clear'),
  capture: () => ipcRenderer.invoke('capture'),
  snip: () => ipcRenderer.send('snip-open'),
  snipDone: (box) => ipcRenderer.send('snip-done', box),
  onCapture: on('capture-result'),
  saveRecording: (data) => ipcRenderer.invoke('save-recording', data),
  reveal: (file) => ipcRenderer.send('reveal', file),
  showStickies: () => ipcRenderer.send('stickies-show'),
  setStickyDock: (on) => ipcRenderer.send('sticky-dock', !!on),
  pick: (kind, multi) => ipcRenderer.invoke('pick', kind, !!multi),
  pdf: (op, files, options) => ipcRenderer.invoke('pdf-run', op, files, options),
  image: (files, options) => ipcRenderer.invoke('image-run', files, options),
  archive: (op, files) => ipcRenderer.invoke('archive-run', op, files),
  rename: (files, options) => ipcRenderer.invoke('rename-run', files, options),
  video: (files, options) => ipcRenderer.invoke('video-run', files, options),
  audio: (files, options) => ipcRenderer.invoke('audio-run', files, options),
  cutBackground: (files) => ipcRenderer.invoke('cutbg-run', files),
  readText: (file) => ipcRenderer.invoke('read-text', file),
  savePicture: (dataUrl, name) => ipcRenderer.invoke('save-picture', dataUrl, name),
  copyText: (text) => ipcRenderer.send('copy-text', text),
  openDraw: () => ipcRenderer.send('draw-open'),
  openStage: (mode) => ipcRenderer.send('stage-open', mode),
  closeStage: () => ipcRenderer.send('stage-close'),
  closeDraw: () => ipcRenderer.send('draw-close'),
  phone: {
    info: () => ipcRenderer.invoke('phone-info'),
    scan: () => ipcRenderer.invoke('phone-scan'),
    openFolder: () => ipcRenderer.send('phone-folder'),
    answer: (id, accept, always) => ipcRenderer.send('phone-answer', id, !!accept, !!always),
    sendFiles: (fingerprint) => ipcRenderer.invoke('phone-send-files', fingerprint),
    sendText: (fingerprint) => ipcRenderer.invoke('phone-send-text', fingerprint),
    onDevices: on('phone-devices'),
    onRequests: on('phone-requests'),
    onEvent: on('phone-event'),
  },
  companion: {
    info: () => ipcRenderer.invoke('companion-info'),
    find: () => ipcRenderer.send('companion-find'),
    pair: (id) => ipcRenderer.send('companion-pair', id),
    answer: (id, accept) => ipcRenderer.send('companion-answer', id, !!accept),
    unpair: (id) => ipcRenderer.send('companion-unpair', id),
    ring: (id) => ipcRenderer.send('companion-ring', id),
    mute: (id) => ipcRenderer.send('companion-mute', id),
    setClipboard: (on) => ipcRenderer.send('companion-clipboard', !!on),
    reply: (id, replyId, message) => ipcRenderer.invoke('companion-reply', id, replyId, message),
    onDevices: on('companion-devices'),
    onPair: on('companion-pair'),
    onNote: on('companion-note'),
    onCall: on('companion-call'),
  },
  vault: {
    status: () => ipcRenderer.invoke('vault-status'),
    reveal: () => ipcRenderer.send('vault-reveal'),
    create: (master) => ipcRenderer.invoke('vault-create', master),
    unlock: (master) => ipcRenderer.invoke('vault-unlock', master),
    lock: () => ipcRenderer.invoke('vault-lock'),
    list: () => ipcRenderer.invoke('vault-list'),
    save: (item) => ipcRenderer.invoke('vault-save', item),
    remove: (id) => ipcRenderer.invoke('vault-remove', id),
    generate: (length, symbols) => ipcRenderer.invoke('vault-generate', length, symbols),
    show: (id) => ipcRenderer.invoke('vault-show', id),
    copy: (id, what) => ipcRenderer.invoke('vault-copy', id, what),
  },
  presence: (p) => ipcRenderer.send('presence', p),
  copyClipPicture: (id) => ipcRenderer.send('clip-copy-picture', id),
  onWinNote: on('win-note'),
  night: (action) => ipcRenderer.invoke('night', action),
  settingsInfo: () => ipcRenderer.invoke('settings-info'),
  placeSearch: (name) => ipcRenderer.invoke('place-search', name),
  shelf: {
    list: () => ipcRenderer.invoke('shelf-list'),
    // Files dropped on the island: the page only has File objects, so their real paths are looked up here.
    addDropped: (files) => ipcRenderer.invoke('shelf-add', Array.from(files || []).map((f) => { try { return webUtils.getPathForFile(f); } catch { return ''; } }).filter(Boolean)),
    pick: () => ipcRenderer.invoke('shelf-pick'),
    remove: (file) => ipcRenderer.invoke('shelf-remove', file),
    clear: () => ipcRenderer.invoke('shelf-clear'),
    reveal: (file) => ipcRenderer.send('shelf-reveal', file),
    drag: (file) => ipcRenderer.send('shelf-drag', file),
    zip: () => ipcRenderer.invoke('shelf-zip'),
    toPhone: () => ipcRenderer.invoke('shelf-phone'),
    onChange: only('shelf'),
  },
  share: {
    info: () => ipcRenderer.invoke('share-info'),
    start: (source) => ipcRenderer.invoke('share-start', source),
    stop: () => ipcRenderer.send('share-stop'),
    toPhone: () => ipcRenderer.invoke('share-to-phone'),
    onChange: only('share'),
  },
  ai: {
    info: () => ipcRenderer.invoke('ai-info'),
    setKey: (key) => ipcRenderer.invoke('ai-key', key),
    setModel: (model) => ipcRenderer.send('ai-model', model),
    ask: (messages) => ipcRenderer.invoke('ai-ask', messages),
    stop: () => ipcRenderer.send('ai-stop'),
    // One listener at a time: the panel replaces it whenever it opens.
    onText: (cb) => { ipcRenderer.removeAllListeners('ai-text'); ipcRenderer.on('ai-text', (_e, piece) => cb(piece)); },
  },
  translateLangs: () => ipcRenderer.invoke('translate-langs'),
  translate: (text, from, to) => ipcRenderer.invoke('translate', text, from, to),
  toggleAwake: () => ipcRenderer.invoke('awake-toggle'),
  lock: () => ipcRenderer.send('lock'),
  radio: (kind, action) => ipcRenderer.invoke('radio', kind, action),
  openSettings: (uri) => ipcRenderer.send('open-settings', uri),
  getStartup: () => ipcRenderer.invoke('startup-get'),
  setStartup: (v) => ipcRenderer.invoke('startup-set', !!v),
});
